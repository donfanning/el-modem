"""Safe, explicit PBX provisioning for El-Modem instances.

This module is deliberately outside the modem worker and DSP path.  The first
adapter manages a small, marked PJSIP include in an existing Asterisk config.
It never rewrites the rest of the PBX configuration.
"""
from __future__ import annotations

import argparse
import difflib
import glob
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import sys
import subprocess
import tempfile
from datetime import datetime, timezone
from typing import Mapping

SCHEMA = 1
INCLUDE_NAME = 'pjsip_elmodem.conf'
BEGIN = '; BEGIN EL-MODEM MANAGED INCLUDE'
END = '; END EL-MODEM MANAGED INCLUDE'
INCLUDE_LINE = f'#include {INCLUDE_NAME}'
FRAGMENT_HEADER = '; Generated by El-Modem. Edit the provisioning map, not this file.'
STATE_POINTER = '.elmodem-provision-current.json'
SAFE_ID = re.compile(r'^[A-Za-z0-9_.-]{1,80}$')
SAFE_SIP_USER = re.compile(r"^[A-Za-z0-9_.!~*'()%+@=\-]{1,128}$")
SAFE_CONTEXT = re.compile(r'^[A-Za-z0-9_.-]{1,80}$')
SAFE_CALLER_ID = re.compile(r'^[A-Za-z0-9 _+.()<>@-]{1,128}$')
ASTERISK_INCLUDE_RE = re.compile(r'^\s*#(?:try)?include\s+["\']?([^"\']+?)["\']?\s*(?:;.*)?$', re.I)


class ProvisionError(ValueError):
    """An unsafe or inconsistent provisioning request."""


def _read_json(path: Path) -> dict:
    try:
        value = json.loads(path.read_text(encoding='utf-8'))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise ProvisionError(f'cannot read JSON file {path}: {exc}') from exc
    if not isinstance(value, dict):
        raise ProvisionError(f'{path} must contain a JSON object')
    return value


def _profile_for(config_path: Path, modem_id: str) -> dict:
    from modem_provisioning import read_saved_network_profile
    try:
        return read_saved_network_profile(config_path,modem_id)
    except ValueError as exc:
        raise ProvisionError(str(exc)) from exc


def load_plan_inputs(config_path: Path, mapping_path: Path) -> tuple[dict, dict, list[dict]]:
    """Load explicit PBX mappings and credentials from opted-in modem profiles."""
    config = _read_json(config_path)
    mapping = _read_json(mapping_path)
    if config.get('schema') != 1 or not isinstance(config.get('modems'), list):
        raise ProvisionError('unsupported El-Modem configuration schema')
    if mapping.get('schema') != SCHEMA:
        raise ProvisionError('unsupported provisioning map schema')
    pbx = mapping.get('pbx')
    bindings = mapping.get('bindings')
    if not isinstance(pbx, dict) or not isinstance(pbx.get('type'),str) or not pbx['type']:
        raise ProvisionError('PBX type must name a configured adapter')
    pbx_host = str(pbx.get('host', '')).strip().casefold()
    try:
        if isinstance(pbx.get('port'), bool):raise ValueError
        pbx_port = int(pbx.get('port', 0))
    except (ValueError, TypeError):
        pbx_port = 0
    if not re.fullmatch(r'(?=.{1,253}$)[A-Za-z0-9.-]+', pbx_host) or pbx_port not in range(1, 65536):
        raise ProvisionError('PBX host and port are required (host name or IPv4, port 1..65535)')
    if not isinstance(bindings, list) or not bindings:
        raise ProvisionError('add at least one explicit modem binding to the provisioning map')

    configured = {}
    for row in config['modems']:
        if not isinstance(row, dict):
            raise ProvisionError('each configured modem must be an object')
        modem_id = row.get('id')
        if modem_id in configured:
            raise ProvisionError(f'duplicate modem instance {modem_id!r}')
        configured[modem_id] = row
    seen_modems: set[str] = set()
    seen_users: set[str] = set()
    endpoints: list[dict] = []
    for binding in bindings:
        if not isinstance(binding, dict):
            raise ProvisionError('each binding must be an object')
        modem_id = str(binding.get('modem', ''))
        if not re.fullmatch(r'modem-[1-9][0-9]*', modem_id) or modem_id not in configured:
            raise ProvisionError(f'unknown modem instance {modem_id!r}')
        if modem_id in seen_modems:
            raise ProvisionError(f'{modem_id} is mapped more than once')
        if configured[modem_id].get('enabled', True) is not True:
            raise ProvisionError(f'{modem_id} is disabled; enable it before provisioning')
        net = _profile_for(config_path, modem_id)
        username = net.get('102', '').strip()
        password = net.get('103', '')
        if not username or not password:
            raise ProvisionError(f'{modem_id} needs both SIP user and password saved before provisioning')
        if any(ord(ch)<32 or ord(ch)==127 for ch in username+password):
            raise ProvisionError(f'{modem_id} SIP account contains control characters')
        registrar = net.get('104', '').strip().casefold()
        registrar_host, separator, registrar_port = registrar.rpartition(':')
        if separator and registrar_port.isdigit():
            registrar_matches = registrar_host == pbx_host and int(registrar_port) == pbx_port
        else:
            registrar_matches = registrar == pbx_host and pbx_port == 5060
        if not registrar_matches:
            raise ProvisionError(f'{modem_id} registrar must target {pbx_host}:{pbx_port}; refusing to copy credentials for a different service')
        if username.casefold() in seen_users:
            raise ProvisionError(f'duplicate SIP username {username!r}')
        caller_id = net.get('105', '').strip()
        if any(ord(ch)<32 or ord(ch)==127 for ch in caller_id):
            raise ProvisionError(f'{modem_id} caller ID contains control characters')
        # Endpoint/auth IDs are instance-derived.  Asterisk requires the AoR
        # name to match the SIP To user on inbound REGISTER, so that one ID is
        # necessarily the account username.
        section = 'elmodem_' + modem_id.replace('-', '_')
        endpoints.append(dict(modem=modem_id, section=section,
                              endpoint=username, username=username,
                              aor=username, password=password, caller_id=caller_id,
                              registrar=net.get('104','').strip()))
        seen_modems.add(modem_id)
        seen_users.add(username.casefold())
    return config, mapping, endpoints


def build_provision_request(config_path: Path, mapping_path: Path,
                            target_override: Path | None = None):
    """Translate saved El-Modem state into the PBX-neutral adapter contract."""
    from modem_provisioning import ModemSipAccount, ProvisionRequest, ProvisionTarget
    _, mapping, endpoints = load_plan_inputs(config_path, mapping_path)
    pbx = dict(mapping['pbx'])
    configured_target = target_override or pbx.get('config_dir')
    if configured_target:
        pbx['config_dir'] = str(Path(configured_target).expanduser().resolve())
    accounts = tuple(ModemSipAccount(
        modem_id=item['modem'], username=item['username'], password=item['password'],
        registrar=item['registrar'], caller_id=item['caller_id']) for item in endpoints)
    target = ProvisionTarget(str(pbx['type']), f"{pbx['host']}:{pbx['port']}", pbx)
    return ProvisionRequest(target, accounts)


def render_pjsip(mapping: dict, endpoints: list[dict]) -> str:
    pbx = mapping['pbx']
    context = pbx['context']
    transport = pbx['transport']
    lines = [
        FRAGMENT_HEADER,
        '; Credentials are sourced from the mapped modem profiles.',
        '',
    ]
    for item in endpoints:
        section = item['section']
        endpoint = item['endpoint']
        auth = section + '_auth'
        aor = item['aor']
        lines.extend([
            f'[{auth}]', 'type=auth', 'auth_type=digest',
            f'username={item["username"]}', f'password={item["password"]}', '',
            f'[{aor}]', 'type=aor', 'max_contacts=1', 'remove_existing=yes',
            'qualify_frequency=30', '',
            f'[{endpoint}]', 'type=endpoint', f'transport={transport}',
            f'context={context}', 'disallow=all', 'allow=ulaw',
            f'auth={auth}', f'aors={aor}', 'direct_media=no',
            'force_rport=yes', 'rewrite_contact=yes', 'rtp_symmetric=yes',
            'identify_by=username',
        ])
        if item['caller_id']:
            lines.append(f'callerid={item["caller_id"]}')
        lines.append('')
    return '\n'.join(lines).rstrip() + '\n'


def managed_include(original: str) -> str:
    newline = '\r\n' if '\r\n' in original else '\n'
    block = newline.join((BEGIN, INCLUDE_LINE, END))
    begin_count = original.count(BEGIN)
    end_count = original.count(END)
    if begin_count != end_count or begin_count > 1:
        raise ProvisionError('Asterisk config has malformed El-Modem include markers')
    if begin_count:
        start = original.index(BEGIN)
        end = original.find(END, start + len(BEGIN))
        if end < 0:
            raise ProvisionError('Asterisk config has malformed El-Modem include markers')
        finish = end + len(END)
        outside=original[:start]+original[finish:]
        if _has_include_line(outside):
            raise ProvisionError(f'{INCLUDE_NAME} is also included outside the El-Modem managed block; review it before applying')
        return original[:start] + block + original[finish:]
    if _has_include_line(original):
        raise ProvisionError(f'{INCLUDE_NAME} is included without El-Modem ownership markers; review it before applying')
    return original.rstrip('\r\n') + (newline * 2 if original.strip() else '') + block + newline


def _has_include_line(original: str) -> bool:
    pattern = r'^\s*#include\s+["\']?' + re.escape(INCLUDE_NAME) + r'["\']?\s*(?:;.*)?$'
    return re.search(pattern, original, re.M) is not None


def has_managed_include(original: str) -> bool:
    begin_count=original.count(BEGIN)
    end_count=original.count(END)
    if begin_count!=1 or end_count!=1:return False
    start=original.index(BEGIN)
    end=original.index(END,start+len(BEGIN))
    finish=end+len(END)
    managed=original[start:finish]
    outside=original[:start]+original[finish:]
    return _has_include_line(managed) and not _has_include_line(outside)


def _asterisk_included_files(main: Path) -> set[Path]:
    """Follow static Asterisk includes without executing configuration directives."""
    pending = [main.resolve()]
    visited: set[Path] = set()
    while pending:
        path = pending.pop()
        if path in visited or not path.is_file():
            continue
        visited.add(path)
        try:
            lines = path.read_text(encoding='utf-8').splitlines()
        except (OSError, UnicodeError) as exc:
            raise ProvisionError(f'cannot inspect included Asterisk file {path}: {exc}') from exc
        for line in lines:
            stripped = line.lstrip()
            if stripped.lower().startswith('#exec'):
                raise ProvisionError(f'{path} uses #exec; remove or review dynamic includes before provisioning')
            match = ASTERISK_INCLUDE_RE.match(line)
            if not match:
                continue
            target = match.group(1).strip()
            if not target:
                continue
            candidate = Path(target)
            if not candidate.is_absolute():
                candidate = path.parent / candidate
            for expanded in glob.glob(str(candidate)):
                pending.append(Path(expanded).resolve())
    return visited


def _defined_objects(main: Path, managed_fragment: Path) -> set[tuple[str, str]]:
    """Return named Asterisk PJSIP objects from statically included files."""
    objects: set[tuple[str, str]] = set()
    for path in _asterisk_included_files(main):
        if path == managed_fragment.resolve():
            continue
        try:
            lines = path.read_text(encoding='utf-8').splitlines()
        except (OSError, UnicodeError) as exc:
            raise ProvisionError(f'cannot inspect included Asterisk file {path}: {exc}') from exc
        section = None
        object_type = None
        def save():
            if section and object_type in ('endpoint', 'aor', 'auth', 'transport'):
                objects.add((object_type, section))
        for line in lines:
            if line.lstrip().startswith((';', '#')):
                continue
            header = re.match(r'^\s*\[([^\]]+)\]', line)
            if header:
                save()
                section = header.group(1).strip()
                object_type = None
                continue
            if section:
                value = re.match(r'^\s*type\s*=\s*([^;#\s]+)', line, re.I)
                if value:
                    object_type = value.group(1).lower()
        save()
    return objects


def _defined_dialplan_contexts(main: Path) -> set[str]:
    """Find static dialplan contexts reachable from extensions.conf includes."""
    contexts=set()
    for path in _asterisk_included_files(main):
        try:
            lines=path.read_text(encoding='utf-8').splitlines()
        except (OSError,UnicodeError) as exc:
            raise ProvisionError(f'cannot inspect included Asterisk dialplan file {path}: {exc}') from exc
        for line in lines:
            if line.lstrip().startswith((';','#')):continue
            match=re.match(r'^\s*\[([^\]]+)\]\s*(?:;.*)?$',line)
            if match:contexts.add(match.group(1).strip())
    return contexts


def ensure_names_available(main: Path, fragment: Path, endpoints: list[dict]) -> None:
    if main.is_symlink() or not main.is_file():
        raise ProvisionError(f'{main} must be an existing regular Asterisk config file')
    if fragment.is_symlink() or (fragment.exists() and not fragment.is_file()):
        raise ProvisionError(f'refusing to replace non-regular managed path {fragment}')
    try:
        main_text=main.read_text(encoding='utf-8')
    except (OSError,UnicodeError) as exc:
        raise ProvisionError(f'cannot inspect {main}: {exc}') from exc
    # Validate ownership before planning as well as before apply. This prevents
    # adopting an include that was added elsewhere without a rollback receipt.
    managed_include(main_text)
    main_resolved=main.resolve()
    fragment_resolved=fragment.resolve()
    main_lines=main_text.splitlines()
    begin_line=main_lines.index(BEGIN) if BEGIN in main_lines else -1
    end_line=main_lines.index(END,begin_line+1) if begin_line>=0 and END in main_lines[begin_line+1:] else -1
    for path in _asterisk_included_files(main):
        if path==main_resolved:
            lines=main_lines
        else:
            try:
                lines=path.read_text(encoding='utf-8').splitlines()
            except (OSError,UnicodeError) as exc:
                raise ProvisionError(f'cannot inspect included Asterisk file {path}: {exc}') from exc
        for line_number,line in enumerate(lines):
            include=ASTERISK_INCLUDE_RE.match(line)
            if not include:continue
            target=Path(include.group(1).strip())
            if not target.is_absolute():target=path.parent/target
            expanded=glob.glob(str(target)) or [str(target)]
            if not any(Path(item).resolve()==fragment_resolved for item in expanded):continue
            owned=(path==main_resolved and begin_line<line_number<end_line and
                   _has_include_line(line))
            if not owned:
                raise ProvisionError(f'{INCLUDE_NAME} is included from {path} outside the El-Modem managed block')
    if fragment.exists():
        if fragment.is_symlink() or not fragment.is_file():
            raise ProvisionError(f'refusing to replace non-regular managed path {fragment}')
        try:
            first_line=fragment.read_text(encoding='utf-8').splitlines()[:1]
        except (OSError,UnicodeError) as exc:
            raise ProvisionError(f'cannot verify ownership of {fragment}: {exc}') from exc
        if first_line != [FRAGMENT_HEADER]:
            raise ProvisionError(f'{fragment} exists but is not marked as El-Modem-managed; refusing to replace it')
    existing = _defined_objects(main, fragment)
    requested = set()
    for item in endpoints:
        requested.update((('auth', item['section'] + '_auth'),
                          ('aor', item['aor']),
                          ('endpoint', item['endpoint'])))
    conflicts = sorted(requested & existing)
    if conflicts:
        rendered = ', '.join(f'{kind} {name}' for kind, name in conflicts)
        raise ProvisionError('Asterisk already defines El-Modem resource name(s): ' + rendered)


def live_registration_status(endpoints: list[dict], *, executable: str = 'asterisk', timeout: float = 3.0) -> list[tuple[str, str]]:
    """Check local Asterisk AoR contacts without exposing SIP secrets."""
    command = shutil.which(executable)
    if not command:
        raise ProvisionError('Asterisk CLI is unavailable; run this check on the PBX host')
    results=[]
    for item in endpoints:
        try:
            completed=subprocess.run([command,'-rx',f'pjsip show aor {item["aor"]}'],
                capture_output=True,text=True,timeout=timeout,check=False)
        except subprocess.TimeoutExpired as exc:
            results.append((item['modem'],'query timed out'))
            continue
        output=(completed.stdout or '')+'\n'+(completed.stderr or '')
        if completed.returncode != 0 or 'Unable to connect to remote asterisk' in output:
            results.append((item['modem'],'Asterisk CLI unavailable'))
        elif 'Unable to find object' in output:
            results.append((item['modem'],'runtime AoR missing'))
        else:
            # `pjsip show aor` always prints a Contact column heading, even
            # when an AoR has no bound contacts. Count only rows with a real
            # AoR/contact URI and retain the Asterisk reachability state.
            contact_states=[]
            for line in output.splitlines():
                match=re.match(r'^\s*Contact:\s+(\S+)\s+(\S+)\s+(\S+)\b',line,re.I)
                if not match:continue
                contact_id=match.group(1).split('/',1)[0]
                if contact_id==item['aor']:
                    contact_states.append(match.group(3))
            if contact_states:
                result='registered contact present ('+', '.join(sorted(set(contact_states)))+')'
            else:
                result='no registered contact'
            results.append((item['modem'],result))
    return results


def live_endpoint_status(endpoints: list[dict], mapping: dict, *,
                         executable: str = 'asterisk', timeout: float = 3.0) -> list[tuple[str, str]]:
    """Compare loaded PJSIP endpoint fields with the generated desired state."""
    command=shutil.which(executable)
    if not command:
        raise ProvisionError('Asterisk CLI is unavailable; run this check on the PBX host')
    expected_context=mapping['pbx']['context']
    expected_transport=mapping['pbx']['transport']
    results=[]
    for item in endpoints:
        try:
            completed=subprocess.run([command,'-rx',f'pjsip show endpoint {item["endpoint"]}'],
                capture_output=True,text=True,timeout=timeout,check=False)
        except subprocess.TimeoutExpired:
            results.append((item['modem'],'Asterisk endpoint query timed out'))
            continue
        output=(completed.stdout or '')+'\n'+(completed.stderr or '')
        endpoint_found=False
        in_auth=None
        aor=None
        transport=None
        configured={}
        for line in output.splitlines():
            match=re.match(r'^\s*Endpoint:\s+(\S+)',line,re.I)
            if match and match.group(1)==item['endpoint']:
                endpoint_found=True
            match=re.match(r'^\s*InAuth:\s+(\S+)',line,re.I)
            if match:in_auth=match.group(1)
            match=re.match(r'^\s*Aor:\s+(\S+)',line,re.I)
            if match and not match.group(1).startswith('<'):
                aor=match.group(1)
            match=re.match(r'^\s*Transport:\s+(\S+)',line,re.I)
            if match and not match.group(1).startswith('<'):
                transport=match.group(1)
            match=re.match(r'^\s*(context|auth|aors)\s*:\s*(.*?)\s*$',line,re.I)
            if match:configured[match.group(1).casefold()]=match.group(2)
        if ('Unable to connect to remote asterisk' in output
                or 'Connection refused' in output):
            results.append((item['modem'],'Asterisk CLI unavailable'))
            continue
        if 'Unable to find object' in output or completed.returncode!=0 or not endpoint_found:
            results.append((item['modem'],'runtime endpoint missing'))
            continue
        expected_auth=item['section']+'_auth'
        mismatches=[]
        if ((in_auth!=f'{expected_auth}/{item["username"]}' and in_auth!=expected_auth)
                or configured.get('auth')!=expected_auth):
            mismatches.append('auth')
        if aor!=item['aor'] or configured.get('aors')!=item['aor']:
            mismatches.append('AoR')
        if transport!=expected_transport:
            mismatches.append('transport')
        if configured.get('context')!=expected_context:
            mismatches.append('context')
        results.append((item['modem'],'runtime endpoint mismatch ('+', '.join(mismatches)+')'
                        if mismatches else 'runtime endpoint matches'))
    return results


class AsteriskPjsipAdapter:
    """File-based adapter for a local Asterisk res_pjsip installation."""
    adapter_id = 'asterisk'

    def plan(self, request):
        from modem_provisioning import ProvisionPlan
        if request.target.adapter_id != self.adapter_id:
            raise ProvisionError(f'{self.adapter_id} adapter cannot plan target {request.target.adapter_id!r}')
        if not isinstance(request.target.settings,Mapping):
            raise ProvisionError('Asterisk target settings must be an object')
        settings=dict(request.target.settings)
        host=str(settings.get('host','')).strip().casefold()
        try:
            if isinstance(settings.get('port'),bool):raise ValueError
            port=int(settings.get('port',0))
        except (TypeError,ValueError):port=0
        if not re.fullmatch(r'(?=.{1,253}$)[A-Za-z0-9.-]+',host) or port not in range(1,65536):
            raise ProvisionError('Asterisk SIP host and port are invalid')
        context=settings.get('context')
        transport=settings.get('transport')
        if not isinstance(context,str) or not SAFE_CONTEXT.fullmatch(context):
            raise ProvisionError('Asterisk context must use letters, digits, dot, underscore, or hyphen')
        if not isinstance(transport,str) or not SAFE_ID.fullmatch(transport):
            raise ProvisionError('Asterisk PJSIP transport name contains unsupported characters')
        if not request.accounts:
            raise ProvisionError('Asterisk request must include at least one modem account')
        seen_modems=set()
        seen_users=set()
        for account in request.accounts:
            if not re.fullmatch(r'modem-[1-9][0-9]*',account.modem_id) or account.modem_id in seen_modems:
                raise ProvisionError('Asterisk request contains an invalid or duplicate modem ID')
            if not SAFE_SIP_USER.fullmatch(account.username):
                raise ProvisionError(f'{account.modem_id} SIP username contains unsupported characters')
            # This is a conservative PJSIP-file serialization limit, not a SIP
            # protocol limit. Reject config delimiters rather than trying to
            # quote user secrets through Asterisk's line-oriented parser.
            if (not account.password or len(account.password)>256 or
                    any(ord(ch)<33 or ord(ch)==127 or ch in ';#[]$\\{}"' for ch in account.password)):
                raise ProvisionError(f'{account.modem_id} SIP password contains unsupported characters')
            registrar=account.registrar.strip().casefold()
            registrar_host,separator,registrar_port=registrar.rpartition(':')
            registrar_matches=((registrar_host==host and registrar_port.isdigit() and int(registrar_port)==port)
                               if separator else (registrar==host and port==5060))
            if not registrar_matches:
                raise ProvisionError(f'{account.modem_id} registrar does not match Asterisk target {host}:{port}')
            if account.username.casefold() in seen_users:
                raise ProvisionError(f'duplicate SIP username {account.username!r}')
            if account.caller_id and not SAFE_CALLER_ID.fullmatch(account.caller_id):
                raise ProvisionError(f'{account.modem_id} caller ID contains unsupported characters')
            seen_modems.add(account.modem_id)
            seen_users.add(account.username.casefold())
        mapping={'pbx':settings}
        endpoints=[dict(modem=account.modem_id,
                         section='elmodem_'+account.modem_id.replace('-','_'),
                         endpoint=account.username,
                         username=account.username,aor=account.username,
                         password=account.password,caller_id=account.caller_id,
                         registrar=account.registrar) for account in request.accounts]
        configured_target=settings.get('config_dir')
        target=Path(configured_target).expanduser().resolve() if configured_target else None
        rendered = render_pjsip(mapping, endpoints)
        warnings = ()
        if target:
            ensure_names_available(target / 'pjsip.conf', target / INCLUDE_NAME, endpoints)
            objects=_defined_objects(target/'pjsip.conf',target/INCLUDE_NAME)
            if ('transport',mapping['pbx']['transport']) not in objects:
                raise ProvisionError(f'Asterisk transport {mapping["pbx"]["transport"]!r} is not defined in statically included PJSIP files')
            dialplan=target/'extensions.conf'
            contexts=_defined_dialplan_contexts(dialplan)
            if mapping['pbx']['context'] not in contexts:
                raise ProvisionError(f'Asterisk dialplan context {mapping["pbx"]["context"]!r} is not defined in statically included extensions.conf files')
        else:
            warnings = ('Asterisk config directory not selected; file conflicts cannot be checked.',)
        summary = tuple(f'{item["modem"]} -> endpoint {item["endpoint"]} / AoR {item["aor"]}'
                        for item in endpoints)
        return ProvisionPlan(self.adapter_id, str(target) if target else None, summary,
                             ({'mapping': mapping, 'endpoints': endpoints, 'target':target,
                               'pjsip': rendered},), warnings)

    def apply(self, plan):
        target=plan.artifacts[0].get('target')
        if plan.adapter_id != self.adapter_id or target is None:
            raise ProvisionError('invalid Asterisk plan or missing config directory')
        artifact = plan.artifacts[0]
        endpoints = artifact['endpoints']
        main=target/'pjsip.conf'
        fragment=target/INCLUDE_NAME
        ensure_names_available(main,fragment,endpoints)
        objects=_defined_objects(main,fragment)
        transport=artifact['mapping']['pbx']['transport']
        if ('transport',transport) not in objects:
            raise ProvisionError(f'Asterisk transport {transport!r} disappeared or is no longer statically included; refusing to apply stale plan')
        contexts=_defined_dialplan_contexts(target/'extensions.conf')
        context=artifact['mapping']['pbx']['context']
        if context not in contexts:
            raise ProvisionError(f'Asterisk dialplan context {context!r} disappeared or is no longer statically included; refusing to apply stale plan')
        return apply_files(target, artifact['pjsip'])

    def check(self, plan, *, live: bool = False):
        from modem_provisioning import ProvisionCheck
        target=plan.artifacts[0].get('target')
        if plan.adapter_id != self.adapter_id or target is None:
            raise ProvisionError('invalid Asterisk plan or missing config directory')
        artifact = plan.artifacts[0]
        fragment = target / INCLUDE_NAME
        main = target / 'pjsip.conf'
        details=[]
        ownership_match=True
        try:
            ensure_names_available(main,fragment,artifact['endpoints'])
        except ProvisionError as exc:
            ownership_match=False
            details.append('El-Modem PJSIP ownership/preflight failed: '+str(exc))
        file_match=fragment.is_file() and fragment.read_text(encoding='utf-8') == artifact['pjsip']
        if file_match:
            fragment_stat=fragment.stat()
            main_stat=main.stat()
            file_match=(fragment_stat.st_uid==main_stat.st_uid and
                        fragment_stat.st_gid==main_stat.st_gid and
                        not (fragment_stat.st_mode & 0o027))
        if file_match:
            details.append('managed PJSIP include matches desired settings and has private permissions')
        else:
            details.append('managed PJSIP include differs from desired settings or has unsafe ownership/permissions')
        include_match=main.is_file() and has_managed_include(main.read_text(encoding='utf-8'))
        if include_match:
            details.append('pjsip.conf includes the managed fragment')
        else:
            details.append('pjsip.conf does not include the managed fragment')
        registrations=tuple(live_registration_status(artifact['endpoints'])) if live else ()
        runtime=tuple(live_endpoint_status(artifact['endpoints'],artifact['mapping'])) if live else ()
        live_match=(not live or
                    all(status=='runtime endpoint matches' for _,status in runtime) and
                    all(status.startswith('registered contact present (') for _,status in registrations))
        return ProvisionCheck(file_match and include_match and ownership_match and live_match,
                              tuple(details),registrations,runtime)

    def rollback(self, target):
        if target.adapter_id != self.adapter_id:
            raise ProvisionError(f'{self.adapter_id} adapter cannot roll back target {target.adapter_id!r}')
        configured_target=target.settings.get('config_dir')
        if not configured_target:
            raise ProvisionError('Asterisk rollback target has no config directory')
        return rollback_files(Path(configured_target).expanduser().resolve())


ADAPTERS = {'asterisk': AsteriskPjsipAdapter}


def adapter_for(kind: str):
    """Select a vendor adapter; FreeSWITCH/Kamailio register behind this contract."""
    adapter = ADAPTERS.get(kind)
    if adapter is None:
        raise ProvisionError(f'PBX adapter {kind!r} is not implemented')
    return adapter()


def _atomic_write(path: Path, content: bytes, mode: int,
                  owner: os.stat_result | tuple[int, int] | None = None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix='.' + path.name + '.', dir=path.parent)
    try:
        if hasattr(os, 'fchmod'):
            os.fchmod(fd, mode)
        if owner is not None and hasattr(os, 'fchown'):
            uid,gid=((owner.st_uid,owner.st_gid) if hasattr(owner,'st_uid') else owner)
            try:
                os.fchown(fd, uid, gid)
            except PermissionError:
                current = os.fstat(fd)
                if (current.st_uid, current.st_gid) != (uid, gid):
                    raise ProvisionError('cannot preserve Asterisk config ownership; run as its config administrator')
        with os.fdopen(fd, 'wb') as output:
            output.write(content)
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def _backup(path: Path) -> Path | None:
    if not path.exists():
        return None
    stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S.%fZ')
    backup = path.with_name(path.name + '.elmodem-' + stamp + '.bak')
    try:
        shutil.copy2(path, backup)
        # Both the generated fragment and the existing PBX file may contain
        # SIP credentials. Backups are owned by the applying user; never
        # inherit a world-readable mode from pjsip.conf.
        os.chmod(backup, 0o600)
    except BaseException as exc:
        try:
            backup.unlink(missing_ok=True)
        except OSError as cleanup_error:
            raise ProvisionError(f'could not secure or remove partial credential backup {backup}: {cleanup_error}') from exc
        raise
    return backup


def _same_file_state(path: Path, previous: os.stat_result | None,
                     expected_content: bytes | None = None) -> bool:
    if previous is None:
        return not path.exists() and not path.is_symlink()
    if path.is_symlink():
        return False
    try:
        current = path.stat()
        content_matches=expected_content is None or path.read_bytes()==expected_content
    except OSError:
        return False
    metadata_matches=(current.st_dev,current.st_ino,current.st_size,current.st_mtime_ns,
                      current.st_uid,current.st_gid,current.st_mode&0o777)==(
        previous.st_dev,previous.st_ino,previous.st_size,previous.st_mtime_ns,
        previous.st_uid,previous.st_gid,previous.st_mode&0o777)
    return metadata_matches and content_matches


def _matches_content_owner_mode(path: Path, content: bytes, mode: int,
                                owner: tuple[int, int]) -> bool:
    if path.is_symlink():
        return False
    try:
        current=path.stat()
        return ((current.st_uid,current.st_gid,current.st_mode&0o777)==
                (owner[0],owner[1],mode) and path.read_bytes()==content)
    except OSError:
        return False


def _file_hash(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _state_pointer(directory: Path) -> tuple[Path, dict | None]:
    pointer=directory/STATE_POINTER
    if pointer.is_symlink():raise ProvisionError('refusing to follow a symlinked provisioning state pointer')
    if not pointer.exists():return pointer,None
    state=_read_json(pointer)
    receipt_name=state.get('receipt')
    if not isinstance(receipt_name,str) or Path(receipt_name).name!=receipt_name or not receipt_name.startswith('.elmodem-provision-'):
        raise ProvisionError('provisioning state pointer is malformed')
    receipt=directory/receipt_name
    if receipt.is_symlink():raise ProvisionError('refusing to follow a symlinked rollback receipt')
    record=_read_json(receipt)
    receipt_schema=record.get('schema')
    if type(receipt_schema) is not int or receipt_schema not in (1,2) or record.get('adapter_id')!='asterisk':
        raise ProvisionError('unsupported provisioning rollback receipt')
    return pointer,record


def rollback_files(asterisk_dir: Path) -> list[Path]:
    """Restore the last managed transaction, but only if its output is untouched."""
    from modem_storage import atomic_json
    directory=asterisk_dir.resolve()
    pointer,record=_state_pointer(directory)
    if record is None:raise ProvisionError('no El-Modem Asterisk transaction is available to roll back')
    try:
        pointer_stat=pointer.stat()
        pointer_content=pointer.read_bytes()
    except OSError as exc:
        raise ProvisionError(f'cannot inspect provisioning state pointer: {exc}') from exc
    if Path(record.get('target','')).resolve()!=directory:
        raise ProvisionError('rollback receipt belongs to a different Asterisk directory')
    main=directory/'pjsip.conf'
    fragment=directory/INCLUDE_NAME
    if main.is_symlink() or fragment.is_symlink():
        raise ProvisionError('refusing to roll back symlinked Asterisk configuration files')
    originals=[]
    for key,path in (('main',main),('fragment',fragment)):
        before=record.get(key,{})
        if not before.get('changed'):continue
        try:
            current=path.stat()
            current_content=path.read_bytes()
        except OSError as exc:raise ProvisionError(f'cannot inspect {path}: {exc}') from exc
        after=before.get('after',{})
        actual=(current.st_uid,current.st_gid,current.st_mode&0o777,
                hashlib.sha256(current_content).hexdigest())
        expected=(after.get('uid'),after.get('gid'),after.get('mode'),after.get('sha256'))
        if actual!=expected:
            raise ProvisionError(f'{path.name} changed after El-Modem applied it; refusing to overwrite later PBX edits')
        backup_name=before.get('backup')
        backup=(directory/backup_name if isinstance(backup_name,str) and
                Path(backup_name).name==backup_name and
                backup_name.startswith(path.name+'.elmodem-') and backup_name.endswith('.bak') else None)
        backup_content=None
        if before.get('existed'):
            if (backup is None or backup.is_symlink() or backup.parent!=directory or
                    backup.resolve().parent!=directory or not backup.is_file()):
                raise ProvisionError(f'rollback backup for {path.name} is missing or unsafe')
            try:
                backup_content=backup.read_bytes()
                backup_stat=backup.stat()
            except OSError as exc:
                raise ProvisionError(f'cannot inspect rollback backup for {path.name}: {exc}') from exc
            expected_backup_hash=before.get('backup_sha256')
            if record.get('schema')>=2 and (
                    not isinstance(expected_backup_hash,str) or
                    hashlib.sha256(backup_content).hexdigest()!=expected_backup_hash):
                raise ProvisionError(f'rollback backup for {path.name} failed its integrity check')
            if record.get('schema')>=2 and (
                    backup_stat.st_uid!=before.get('backup_uid') or
                    backup_stat.st_gid!=before.get('backup_gid') or
                    (backup_stat.st_mode&0o777)!=before.get('backup_mode')):
                raise ProvisionError(f'rollback backup for {path.name} has changed ownership or permissions')
        originals.append((path,before,backup,current,current_content,backup_content))
    # All preconditions are checked before restoring either file.
    restored=[]
    try:
        for path,before,backup,current,current_content,backup_content in originals:
            if not _same_file_state(path,current,current_content):
                raise ProvisionError(f'{path.name} changed during rollback preflight; refusing to overwrite it')
            if before.get('existed'):
                owner=(int(before['uid']),int(before['gid']))
                mode=int(before['mode'])
                _atomic_write(path,backup_content,mode,owner)
                restored.append((path,backup_content,mode,owner,current,current_content))
            else:
                path.unlink(missing_ok=True)
                restored.append((path,None,None,None,current,current_content))
        previous=record.get('previous_receipt')
        if not _same_file_state(pointer,pointer_stat,pointer_content):
            raise ProvisionError('provisioning state changed during rollback; refusing to replace its pointer')
        if (isinstance(previous,str) and Path(previous).name==previous
                and previous.startswith('.elmodem-provision-')
                and (directory/previous).is_file() and not (directory/previous).is_symlink()):
            atomic_json(pointer,{'schema':1,'receipt':previous})
        else:
            pointer.unlink(missing_ok=True)
    except BaseException as exc:
        compensation_failed=False
        for path,restored_content,restored_mode,restored_owner,current,current_content in reversed(restored):
            try:
                if restored_content is None:
                    if path.exists() or path.is_symlink():
                        compensation_failed=True
                        continue
                elif not _matches_content_owner_mode(path,restored_content,restored_mode,restored_owner):
                    compensation_failed=True
                    continue
                _atomic_write(path,current_content,current.st_mode&0o777,
                              (current.st_uid,current.st_gid))
            except (OSError,ProvisionError):
                compensation_failed=True
        if compensation_failed:
            raise ProvisionError('rollback failed and could not fully restore its pre-rollback files; inspect Asterisk config and retained backups') from exc
        raise ProvisionError('rollback failed; its partial file changes were reverted') from exc
    return [entry[0] for entry in restored]


def apply_files(asterisk_dir: Path, rendered: str) -> list[Path]:
    """Install the managed include and PJSIP fragment with backups."""
    from modem_storage import atomic_json
    main = asterisk_dir / 'pjsip.conf'
    fragment = asterisk_dir / INCLUDE_NAME
    if main.is_symlink() or fragment.is_symlink():
        raise ProvisionError('refusing to replace symlinked Asterisk configuration files')
    if not main.is_file():
        raise ProvisionError(f'{main} does not exist; refusing to create a new PBX config')
    try:
        main_stat = main.stat()
        previous_main = main.read_bytes()
        main_text = previous_main.decode('utf-8')
    except (OSError, UnicodeError) as exc:
        raise ProvisionError(f'cannot read {main}: {exc}') from exc
    new_main = managed_include(main_text).encode('utf-8')
    fragment_stat = fragment.stat() if fragment.exists() else None
    old_fragment = fragment.read_bytes() if fragment_stat else None
    main_mode = main_stat.st_mode & 0o777
    fragment_mode = main_mode & 0o640
    fragment_owner = main_stat
    main_changed = new_main != previous_main
    fragment_changed = (old_fragment != rendered.encode('utf-8') or fragment_stat is None or
        (fragment_stat.st_uid,fragment_stat.st_gid,fragment_stat.st_mode&0o777) !=
        (main_stat.st_uid,main_stat.st_gid,fragment_mode))
    if not main_changed and not fragment_changed:return []
    pointer,previous_record=_state_pointer(asterisk_dir)
    previous_receipt=_read_json(pointer).get('receipt') if previous_record is not None else None
    main_backup=_backup(main) if main_changed else None
    fragment_backup=_backup(fragment) if fragment_changed and fragment_stat else None
    backups=[path for path in (main_backup,fragment_backup) if path]
    stamp=datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S.%fZ')
    receipt=asterisk_dir/f'.elmodem-provision-{stamp}.json'
    if receipt.exists():raise ProvisionError('rollback receipt name collision; retry apply')
    try:
        if (not _same_file_state(main,main_stat,previous_main) or
                not _same_file_state(fragment,fragment_stat,old_fragment)):
            raise ProvisionError('Asterisk configuration changed during planning; rerun the command')
        if fragment_changed:_atomic_write(fragment, rendered.encode('utf-8'), fragment_mode, fragment_owner)
        if main_changed:_atomic_write(main, new_main, main_mode, main_stat)
        def prior(path_stat,backup):
            record=dict(existed=path_stat is not None,
                backup=backup.name if backup else None,
                uid=path_stat.st_uid if path_stat else None,
                gid=path_stat.st_gid if path_stat else None,
                mode=(path_stat.st_mode&0o777) if path_stat else None)
            if backup:
                backup_stat=backup.stat()
                record.update(backup_uid=backup_stat.st_uid,backup_gid=backup_stat.st_gid,
                              backup_mode=backup_stat.st_mode&0o777,
                              backup_sha256=_file_hash(backup))
            return record
        record=dict(schema=2,adapter_id='asterisk',target=str(asterisk_dir.resolve()),
                    previous_receipt=previous_receipt,
                    main=prior(main_stat,main_backup),fragment=prior(fragment_stat,fragment_backup))
        for key,path,changed in (('main',main,main_changed),('fragment',fragment,fragment_changed)):
            record[key]['changed']=changed
            if changed:
                st=path.stat()
                record[key]['after']=dict(uid=st.st_uid,gid=st.st_gid,mode=st.st_mode&0o777,
                                          sha256=_file_hash(path))
        atomic_json(receipt,record)
        atomic_json(pointer,{'schema':1,'receipt':receipt.name})
    except BaseException:
        # Best-effort rollback if the second file write fails.
        if fragment_changed:
            if old_fragment is None:fragment.unlink(missing_ok=True)
            else:_atomic_write(fragment,old_fragment,fragment_stat.st_mode&0o777,fragment_stat)
        if main_changed:_atomic_write(main,previous_main,main_mode,main_stat)
        receipt.unlink(missing_ok=True)
        raise
    return backups


def _summary(endpoints: list[dict]) -> str:
    return '\n'.join(f'  {item["modem"]} -> endpoint {item["endpoint"]} '
                     f'(SIP user {item["username"]}, password configured)' for item in endpoints)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog='el-modem provision',
        description='Plan and reconcile El-Modem-owned PBX resources.')
    parser.add_argument('action', choices=('plan', 'apply', 'check', 'rollback'))
    parser.add_argument('--config', help='El-Modem supervisor config.json')
    parser.add_argument('--map', help='explicit telephony mapping JSON')
    parser.add_argument('--asterisk-dir', help='Asterisk config directory (overrides the path saved in the map)')
    parser.add_argument('--live',action='store_true',help='query loaded PJSIP endpoints and AoR contacts on the local Asterisk host')
    args = parser.parse_args(argv)
    try:
        if args.live and args.action != 'check':
            raise ProvisionError('--live is available only with the check action')
        if args.action == 'rollback':
            if not args.asterisk_dir:
                raise ProvisionError('rollback requires --asterisk-dir')
            from modem_provisioning import ProvisionTarget
            directory=Path(args.asterisk_dir).expanduser().resolve()
            target=ProvisionTarget('asterisk',str(directory),{'config_dir':str(directory)})
            restored=adapter_for('asterisk').rollback(target)
            print('Restored the last El-Modem transaction:')
            for path in restored:print(f'  {path}')
            print('Review Asterisk configuration, then reload PJSIP through the normal administration path.')
            return 0
        if not args.config or not args.map:
            raise ProvisionError(f'{args.action} requires --config and --map')
        config_path = Path(args.config).expanduser().resolve()
        mapping_path = Path(args.map).expanduser().resolve()
        mapping = _read_json(mapping_path)
        pbx = mapping.get('pbx', {})
        if not isinstance(pbx, dict):raise ProvisionError('PBX mapping must be an object')
        adapter = adapter_for(str(pbx.get('type', '')))
        override = Path(args.asterisk_dir).expanduser() if args.asterisk_dir else None
        plan = adapter.plan(build_provision_request(config_path,mapping_path,override))
        print(f'{plan.adapter_id} provisioning plan (secret values are masked):')
        print('\n'.join('  '+line for line in plan.summary))
        for warning in plan.warnings:print('WARNING: '+warning)
        if args.action == 'plan':
            target=plan.artifacts[0].get('target')
            if target:
                current = target / INCLUDE_NAME
                if current.is_file():
                    old = current.read_text(encoding='utf-8').splitlines(keepends=True)
                    new = plan.artifacts[0]['pjsip'].splitlines(keepends=True)
                    def redact(lines):
                        return [re.sub(r'(?i)(password\s*=).*', r'\1<redacted>\n', line)
                                if re.match(r'(?i)\s*password\s*=', line) else line for line in lines]
                    print(''.join(difflib.unified_diff(redact(old), redact(new),
                                                        fromfile=str(current), tofile='planned')))
                else:
                    print(f'  create {current}')
                print(f'  add managed include to {target / "pjsip.conf"}')
            else:
                print('Choose a PBX config directory to inspect and preview file changes.')
            return 0
        if args.action == 'check':
            report=adapter.check(plan,live=args.live)
            for detail in report.details:print('  '+detail)
            for modem,status in report.runtime:print(f'  {modem} loaded endpoint: {status}')
            for modem,status in report.registrations:print(f'  {modem}: {status}')
            if not args.live:print('Use --live to query loaded endpoint configuration and registration contacts from the PBX CLI.')
            print('RESULT: '+('consistent' if report.consistent else 'inconsistent'))
            return 0 if report.consistent else 1
        backups = adapter.apply(plan)
        target=plan.artifacts[0]['target']
        fragment=target/INCLUDE_NAME
        main_config=target/'pjsip.conf'
        print(f'Wrote {fragment} with private permissions inherited from the Asterisk config.')
        print(f'Updated {main_config} only inside the El-Modem managed include block.')
        for backup in backups:
            print(f'Backup: {backup}')
        print('Review the generated include, then reload Asterisk with: asterisk -rx "pjsip reload"')
        print('This command does not run as root, reload Asterisk, or change the dialplan.')
        return 0
    except (ProvisionError, OSError) as exc:
        print(f'provisioning error: {exc}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
