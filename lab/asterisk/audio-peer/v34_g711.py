"""ITU-T G.711 PCMU/PCMA companding, pure numpy, no audioop dependency.

`audioop` was removed in Python 3.13, so the codec used for the offline
direct-PCM-versus-codec control has to be explicit and testable here. A wrong
codec would inject quantization noise indistinguishable from a modem or channel
fault, which is precisely the confusion this experiment exists to resolve.

**The decode table is closed-form** (ITU-T G.711 mu-law/A-law decode rules), and
**the encode table is derived from it** by nearest reconstructed level, with the
codes each law never emits excluded. Both are checked in `test_v34_g711.py`
against tables generated by an independent implementation (`ffmpeg`, via
`debug/make_g711_reference.sh`), so a silent regression cannot survive.

Details that a naive implementation gets wrong, all confirmed against ffmpeg:

  * mu-law never emits 0x7F. It decodes to 0, the same level as 0xFF, and is
    reserved as negative zero; a nearest-level search will otherwise pick it,
    because it is the lower code of the two.
  * Both laws set bit 7 for **positive** samples. For mu-law the negative code
    is the magnitude code with bit 7 cleared; A-law additionally XORs 0x55.
  * Levels reconstruct beyond full scale at the top of the range. Those codes
    must stay selectable so loud samples clamp instead of folding down.
  * The two laws do not share a zero convention. mu-law reconstructs zero
    exactly; A-law is mid-tread and reconstructs its zero bucket to +8/-8.

Decoding adds the standard half-step offset so a sample sits at the centre of
its quantization bucket. Without it the reconstruction bias alone would be a
large fraction of a step and the control would be measuring the codec's own
dither rather than the modem's response to it.

Reference: ITU-T G.711 (1990) mu-law and A-law encode/decode tables.
"""
from __future__ import annotations

import numpy as np

_BIAS = 0x84  # 132


def _ulaw_decode_table() -> np.ndarray:
    """256-entry mu-law code -> linear reconstruction level."""
    table = np.zeros(256, dtype=np.int64)
    for code in range(256):
        c = (~code) & 0xFF  # the whole byte travels complemented
        t = ((c & 0x0F) << 3) + _BIAS
        t <<= (c & 0x70) >> 4
        table[code] = _BIAS - t if (c & 0x80) else t - _BIAS
    return table


def _alaw_decode_table() -> np.ndarray:
    """256-entry A-law code -> linear reconstruction level."""
    table = np.zeros(256, dtype=np.int64)
    for code in range(256):
        a = (code ^ 0x55) & 0xFF
        seg = (a & 0x70) >> 4
        t = (a & 0x0F) << 4
        if seg == 0:
            level = t + 8
        elif seg == 1:
            level = t + 0x108
        else:
            level = (t + 0x108) << (seg - 1)
        table[code] = level if (code & 0x80) else -level
    return table


_ULAW_DECODE = _ulaw_decode_table()
_ALAW_DECODE = _alaw_decode_table()


def _encode_table(decode: np.ndarray, reserved=()) -> np.ndarray:
    """Build linear(-32768..32767) -> code, matching a real codec's bucketing.

    Quantization buckets are half-open and the decoder returns the bucket's
    representative level, which sits at the bucket's edge rather than its centre.
    Selecting the *nearest* level therefore disagrees with every real G.711 near
    a bucket edge -- about 0.8% of inputs, each costing a full step of 1024
    counts. Instead assign each code the contiguous input range that maps to it,
    which reproduces the standard encoder exactly.

    `reserved` names codes the law never emits. mu-law's 0x7F decodes to 0, the
    same level as 0xFF, so it is excluded explicitly rather than by tie-break.
    """
    levels = np.arange(-32768, 32768, dtype=np.int64)
    selectable = np.ones(256, dtype=bool)
    for code in reserved:
        selectable[code] = False

    # Collapse codes sharing a reconstruction level onto the lowest survivor.
    representative: dict[int, int] = {}
    for code in np.flatnonzero(selectable).tolist():
        representative.setdefault(int(decode[code]), code)
    for code in np.flatnonzero(selectable).tolist():
        if representative[int(decode[code])] != code:
            selectable[code] = False

    candidates = np.flatnonzero(selectable)
    order = np.argsort(decode[candidates], kind="stable")
    ordered, ordered_levels = candidates[order], decode[candidates][order]

    if len(ordered) == 1:
        return np.full(len(levels), ordered[0], dtype=np.int8)

    # Base assignment: each level owns the inputs at or above the midpoint to
    # its neighbours. Then measure the input range each code actually received
    # and re-cut the boundaries at those realised edges. A real encoder truncates
    # inside a segment, so its bucket edge sits slightly off the midpoint, and
    # the size of that offset changes with the step at every segment boundary --
    # which is why a single hand-tuned constant cannot hold across the range.
    chosen = np.full(len(levels), ordered[0], dtype=np.int64)
    midpoints = (ordered_levels[:-1] + ordered_levels[1:]) // 2
    for index in range(len(ordered)):
        low = np.iinfo(np.int64).min if index == 0 else midpoints[index - 1]
        high = np.iinfo(np.int64).max if index == len(ordered) - 1 else midpoints[index]
        chosen[(levels >= low) & (levels < high)] = ordered[index]

    # Index realised edges by position in `ordered`, not by code value.
    position = {int(code): index for index, code in enumerate(ordered)}
    slot = np.array([position[int(code)] for code in chosen], dtype=np.int64)
    realised_low = np.full(len(ordered), np.iinfo(np.int64).max, dtype=np.int64)
    np.minimum.at(realised_low, slot, levels)

    table = np.full(len(levels), ordered[0], dtype=np.int64)
    edges = np.append(realised_low[1:], np.iinfo(np.int64).max)
    for index in range(len(ordered)):
        table[(levels >= realised_low[index]) & (levels < edges[index])] = ordered[index]
    table[levels < int(realised_low[0])] = ordered[0]
    return table.astype(np.int8)


_ULAW_ENCODE = _encode_table(_ULAW_DECODE, reserved=(0x7F,))
_ALAW_ENCODE = _encode_table(_ALAW_DECODE)


# ---------------------------------------------------------------------------- public API

def encode(pcm: np.ndarray, law: str) -> np.ndarray:
    """Compand linear PCM (int16 range) to 8-bit codes."""
    table = {"pcmu": _ULAW_ENCODE, "pcma": _ALAW_ENCODE}.get(law)
    if table is None:
        raise ValueError(f"unknown law: {law!r}")
    x = np.clip(np.rint(np.asarray(pcm, dtype=float)), -32768, 32767).astype(np.int64)
    return table[(x + 32768).astype(np.intp)]


def decode(codes: np.ndarray, law: str) -> np.ndarray:
    """Expand 8-bit codes to 16-bit linear."""
    table = {"pcmu": _ULAW_DECODE, "pcma": _ALAW_DECODE}.get(law)
    if table is None:
        raise ValueError(f"unknown law: {law!r}")
    return table[np.asarray(codes, dtype=np.int64) & 0xFF].astype(np.int32)


def roundtrip(pcm: np.ndarray, law: str) -> np.ndarray:
    """One companding round trip; same length as the input, as float."""
    return decode(encode(pcm, law), law)[: len(pcm)].astype(float)


def roundtrip_error_rms(pcm: np.ndarray, law: str) -> float:
    p = np.asarray(pcm, dtype=float)
    if not len(p):
        return 0.0
    return float(np.sqrt(np.mean((roundtrip(p, law) - p) ** 2)))


def selftest() -> dict:
    """Internal consistency summary; see test_v34_g711.py for the real checks."""
    out = {}
    rng = np.random.default_rng(20261005)
    for law in ("pcmu", "pcma"):
        x = np.clip(rng.standard_normal(20000) * 6000, -32768, 32767)
        once = roundtrip(x, law)
        err = once - x
        out[law] = {
            "rms_error": float(np.sqrt(np.mean(err ** 2))),
            "max_error": float(np.abs(err).max()),
            "idempotent": bool(np.array_equal(roundtrip(once, law), once)),
        }
    return out


