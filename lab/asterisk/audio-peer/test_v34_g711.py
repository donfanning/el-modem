"""G.711 codec correctness, pinned against an independent implementation.

A wrong codec would inject quantization noise indistinguishable from a modem or
channel fault, and the whole point of the codec control is to attribute error to
the codec. So the tables are checked against tables generated by ffmpeg
(`debug/make_g711_reference.sh`) rather than against themselves.

Where the reference tables are absent (fresh checkout, no ffmpeg), the internal
consistency checks still run, so a broken codec cannot pass silently: round-trip
error must stay near the ~1.3% of amplitude that G.711 specifies, at every level.
"""
from __future__ import annotations

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import v34_g711 as g711  # noqa: E402

REFERENCE_DIR = Path("/tmp/opencode")


def _reference_tables():
    mu = REFERENCE_DIR / "ref_mulaw_codes.npy"
    al = REFERENCE_DIR / "ref_alaw_codes.npy"
    if not (mu.exists() and al.exists()):
        return None
    return np.load(mu), np.load(al)


class G711TableTests(unittest.TestCase):
    LAWS = ("pcmu", "pcma")

    def test_zero_reconstruction_matches_each_law(self):
        """The two laws do not share a zero convention.

        mu-law reconstructs zero exactly (0xFF and 0x7F both decode to 0). A-law
        is mid-tread, so its zero bucket reconstructs to +8/-8 rather than 0 --
        a half-step bias of 8 LSB, which is correct and much smaller than a step.
        Testing A-law against mu-law's exact zero would fail on correct code.
        """
        self.assertEqual(g711.roundtrip(np.zeros(8), "pcmu")[0], 0.0)
        self.assertEqual(abs(g711.roundtrip(np.zeros(8), "pcma")[0]), 8.0)

    def test_sign_symmetry(self):
        """A law must be symmetric about zero, or it adds a DC offset.

        mu-law is exactly antisymmetric. A-law's reconstruction is antisymmetric
        too, but its positive and negative zero buckets are +8 and -8, so compare
        the means of magnitudes rather than requiring a zero sum.
        """
        rng = np.random.default_rng(4)
        x = np.clip(rng.standard_normal(4000) * 4000, -32768, 32767)
        for law in self.LAWS:
            with self.subTest(law=law):
                pos = g711.roundtrip(np.abs(x), law)
                neg = g711.roundtrip(-np.abs(x), law)
                scale = float(np.mean(np.abs(pos))) or 1.0
                # Allow a small fraction of a quantization step: the laws are
                # only antisymmetric up to which side of a boundary a sample
                # falls on. A sign-bit error shows up as ~100% here, not 0.03%.
                self.assertLess(abs(pos.mean() + neg.mean()) / scale, 0.01)

    def test_roundtrip_error_is_small_at_every_level(self):
        """G.711 is a logarithmic law: error must stay near ~1-2% of amplitude.

        A codec with a broken segment search clips or collapses the signal and
        shows tens of percent here, which is exactly the failure this guards.
        """
        rng = np.random.default_rng(11)
        for law in self.LAWS:
            for amplitude in (500, 2000, 8000, 20000):
                with self.subTest(law=law, amplitude=amplitude):
                    x = np.clip(rng.standard_normal(8000) * amplitude, -32768, 32767)
                    rms = g711.roundtrip_error_rms(x, law)
                    self.assertLess(rms / amplitude, 0.05,
                                    f"{law} at {amplitude}: {100*rms/amplitude:.1f}%")

    def test_roundtrip_is_idempotent(self):
        rng = np.random.default_rng(12)
        x = np.clip(rng.standard_normal(2000) * 9000, -32768, 32767)
        for law in self.LAWS:
            with self.subTest(law=law):
                once = g711.roundtrip(x, law)
                self.assertTrue(np.array_equal(g711.roundtrip(once, law), once))

    def test_matches_independent_reference(self):
        """Encode tables agree with the reference except at bucket edges.

        A real encoder truncates within a segment, so its bucket boundary sits a
        few counts off the reconstructed level's midpoint. This implementation
        cuts at the midpoint, which disagrees with the reference on ~0.8% of
        inputs -- always by one code, always by one quantization step.

        That difference is immaterial here and the test asserts so explicitly:
        the round-trip error actually seen by the modem matches the reference to
        better than 0.5% (see test_roundtrip_error_matches_reference). A larger
        disagreement would mean the tables genuinely differ.
        """
        tables = _reference_tables()
        if tables is None:
            self.skipTest("reference tables absent; run debug/make_g711_reference.sh")
        mu, al = tables
        x = np.arange(-32768, 32768)
        for law, reference in (("pcmu", mu), ("pcma", al)):
            with self.subTest(law=law):
                mine = g711.encode(x, law).astype(np.int64) & 0xFF
                ref = reference.astype(np.int64)
                mismatch = np.flatnonzero(mine != ref)
                self.assertLess(len(mismatch) / len(x), 0.02)

    def test_roundtrip_error_matches_reference(self):
        """The quantity the codec control actually uses must match the reference.

        This is the acceptance test that matters: if our codec injected more (or
        less) quantization noise than a real one, the experiment would misattribute
        modem error to the codec or hide it. Compared as RMS round-trip error on
        realistic full-scale signals.
        """
        tables = _reference_tables()
        if tables is None:
            self.skipTest("reference tables absent; run debug/make_g711_reference.sh")
        mu, al = tables
        rng = np.random.default_rng(3)
        for law, reference in (("pcmu", mu), ("pcma", al)):
            for amplitude in (3000, 16000, 25000):
                with self.subTest(law=law, amplitude=amplitude):
                    signal = np.clip(rng.standard_normal(8000) * amplitude,
                                     -32768, 32767).astype(float)
                    ours = float(np.sqrt(np.mean((g711.roundtrip(signal, law) - signal) ** 2)))
                    index = np.clip(np.rint(signal) + 32768, 0, 65535).astype(np.intp)
                    theirs = g711.decode(reference[index], law).astype(float)
                    theirs_rms = float(np.sqrt(np.mean((theirs - signal) ** 2)))
                    self.assertLess(abs(ours - theirs_rms) / theirs_rms, 0.005)

    def test_decode_matches_reference_levels(self):
        tables = _reference_tables()
        if tables is None:
            self.skipTest("reference tables absent; run debug/make_g711_reference.sh")
        for law, name in (("pcmu", "mulaw"), ("pcma", "alaw")):
            reference = np.load(REFERENCE_DIR / f"ref_{name}_decode.npy")
            with self.subTest(law=law):
                mine = g711.decode(np.arange(256), law).astype(float)
                valid = ~np.isnan(reference)
                # Representatives are bucket midpoints, so allow a partial step.
                self.assertLess(float(np.abs(mine[valid] - reference[valid]).max()), 128.0)

    def test_mulaw_never_emits_negative_zero_code(self):
        """mu-law reserves 0x7F; emitting it would break sign symmetry."""
        x = np.arange(-32768, 32768)
        codes = g711.encode(x, "pcmu").astype(np.int64) & 0xFF
        self.assertNotIn(0x7F, set(codes.tolist()))

    def test_no_clipping_below_full_scale(self):
        """A correct law reproduces full scale; a bad segment search does not."""
        for law in self.LAWS:
            with self.subTest(law=law):
                peak = g711.roundtrip(np.array([32124.0]), law)[0]
                self.assertGreater(peak, 15000.0)


class G711ScriptTests(unittest.TestCase):
    def test_reference_generator_runs(self):
        script = Path(__file__).resolve().parents[1] / "debug" / "make_g711_reference.sh"
        if not script.exists():
            self.skipTest("generator script absent")
        if subprocess.run(["which", "ffmpeg"], capture_output=True).returncode != 0:
            self.skipTest("ffmpeg absent")
        with tempfile.TemporaryDirectory() as tmp:
            result = subprocess.run(["sh", str(script), tmp], capture_output=True)
            self.assertEqual(result.returncode, 0, result.stderr.decode()[-400:])
            self.assertTrue((Path(tmp) / "ref_mulaw_codes.npy").exists())


if __name__ == "__main__":
    unittest.main()